# PlatformIO pre-script for the provision env: turns the device's AWS credentials into a C
# header inside the build directory (never in src/, never committed).
#
# Reads custom_certs_dir and custom_device_id from platformio.ini (both come from secrets.ini).
Import("env")  # noqa: F821  (provided by SCons)

import os
import sys

FILES = {
    "kProvisionCaPem": "AmazonRootCA1.pem",
    "kProvisionCertPem": "device.pem.crt",
    "kProvisionKeyPem": "private.pem.key",
}
DELIM = "PEM"


def fail(msg):
    sys.stderr.write("embed_certs: %s\n" % msg)
    env.Exit(1)  # noqa: F821


project_dir = env.subst("$PROJECT_DIR")  # noqa: F821
certs_dir = env.GetProjectOption("custom_certs_dir", "")  # noqa: F821
device_id = env.GetProjectOption("custom_device_id", "")  # noqa: F821
if not certs_dir:
    fail("custom_certs_dir is not set (secrets.ini → certs_dir)")
certs_dir = os.path.normpath(os.path.join(project_dir, certs_dir))

# The backend's provisioning script names the folder after the thing; catch a mismatch before
# the wrong key lands in the modem.
if os.path.basename(certs_dir) != device_id:
    fail("certs_dir %s does not belong to device_id %s" % (certs_dir, device_id))

lines = [
    "// Generated by scripts/embed_certs.py for %s. Contains a private key: do not commit." % device_id,
    "#pragma once",
    "",
]
for symbol, name in FILES.items():
    path = os.path.join(certs_dir, name)
    if not os.path.isfile(path):
        fail("missing %s" % path)
    with open(path, "r", encoding="ascii") as f:
        pem = f.read()
    if "-----BEGIN" not in pem:
        fail("%s is not PEM" % path)
    if ")" + DELIM + '"' in pem:
        fail("%s contains the raw-string delimiter" % path)
    lines.append('static const char %s[] = R"%s(%s)%s";' % (symbol, DELIM, pem, DELIM))
    lines.append("")

out_dir = os.path.join(env.subst("$BUILD_DIR"), "generated")  # noqa: F821
os.makedirs(out_dir, exist_ok=True)
out_path = os.path.join(out_dir, "provision_certs.h")
with open(out_path, "w", encoding="ascii") as f:
    f.write("\n".join(lines))
os.chmod(out_path, 0o600)

env.Append(CPPPATH=[out_dir])  # noqa: F821
print("embed_certs: embedded credentials for %s" % device_id)
